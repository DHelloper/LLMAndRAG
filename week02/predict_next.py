"""
진짜 신경망으로 '다음 숫자 맞히기'
앞의 예제는 파라미터가 1개였다. 여기서는 수십 개 짜리 2층 신경망을 쓴다.
구조만 커질 뿐 학습 방식(순전파 -> 손실 -> 역전파 -> 갱신)은 완전히 동일하다.

[풀려는 문제]
연속한 세 수를 주면 다음 수를 맞혀라. [1,2,3] -> 4

[이 파일에서 꼭 볼 것]
1. 학습 루프 5줄 - 4주차 Mini GPT도 정확히 이 5줄이다.
2. 비선형(Tanh)이 없으면 층을 쌓는 의미가 사라진다는 것
3. 학습 범위 밖 입력에서 크게 빗나간다는 것 (일반화의 한계)

"""

import torch
import torch.nn as nn

# 난수 시드 고정. 신경망의초기 가중치는 무작위라서 고정하지 않으면 실행할 때 마다 결과가 달라져 비교가 불가능하다.
torch.manual_seed(42)

# ─── 데이터 ───────────────────────────────────────────────
# X: 입력 5묶음, 각 묶음은 숫자 3개 -> shape (5, 3)
# Y: 정답 5개, 각각 숫자 1개 -> shape (5, 1)
#
# Y 를 [[4.],[5.]] 처럼 2중 대괄호로 쓰는 이유:
# 모델 출력이 (5,1) 이라서 정답도 (5,1) 로 모양을 맞춰야 한다.
# [4.,5.,...] 로 쓰면 (5,) 가 되어 브로드캐스팅 경고가 뜨고 손실이 엉뚱해진다.

X = torch.tensor([[1., 2., 3.],
[2., 3., 4.],
[3., 4., 5.],
[4., 5., 6.],
[5., 6., 7.]])
Y = torch.tensor([[4.], [5.], [6.], [7.], [8.]])

# ─── 모델 ─────────────────────────────────────────────────
# nn.Sequential : 넣은 순서대로 데이터를 통과시키는 상자
#
# 데이터가 흘러가는 모양:
# (5,3) --Linear(3,8)--> (5,8) --Tanh--> (5,8) --Linear(8,1)--> (5,1)
model = nn.Sequential(
    # Linear(3, 8) : 입력 3개를 받아 8개를 만든다.
    # 내부적으로 y = xW + b를 계산한다. W는 (3,8), b 는 (8,) 짜리 학습 대상.
    nn.Linear(3,8),

    # Tanh : 비선형 함수. 입력을 -1~1 사이로 구부린다.
    #
    # ★ 이게 없으면 층을 쌓는 의미가 사라진다.
    # Linear 는 행렬곱이고, 행렬곱을 두 번 해도 결국 행렬곱 한 번으로 합쳐진다.
    # (xW1)W2 = x(W1W2) = xW3. 즉 2층이 1층과 수학적으로 완전히 같아진다.
    # 중간에 '곧은 선이 아닌 것'을 끼워야 비로소 복잡한 관계를 표현할 수 있다.
    # 3주차 Transformer 의 Feed Forward 에도 같은 이유로 비선형이 들어간다.
    nn.Tanh(),

    # Linear(8, 1) : 8개를 받아 최종 예측 값 1개를 만든다.
    nn.Linear(8, 1),
)

# 손실 함수 : MSE = Mean Squared Error = 평균 제곱 오차
# 예측과 정답 차이를 제곱해 평균낸다. 앞 예제의 (y-t)^2 를 여러 개로 확장한 것.
loss_fn = nn.MSELoss()

# 옵티마이저 : 갱신 규칙을 담당하는 객체
# model.parameters() 로 학습 대상 (W, b 전부)을 넘겨주면
# step() 호출 시 알아서 w = w - lr*grad를 적용해 준다.
# SGD = Stochastic Gradient Descent
optimizer = torch.optim.SGD(model.parameters(), lr=0.01)

# ─── 학습 루프 ────────────────────────────────────────────
# epoch = 전체 데이터를 한 번 훑는 것. 여기선 데이터가 작아 2001번 반복한다.

for epoch in range(40001) :
    # 1. 순전파 - 현재 가중치로 예측
    pred = model(X)

    # 2. 손실 - 얼마나 틀렸는지
    loss = loss_fn(pred, Y)

    # 3. gradient 초기화 - 이전 회차 값이 남아 더해지는 것을 막는다.
    # set_to_none 없이 그냥 zero_grad()를 써도 된다.
    optimizer.zero_grad()

    # 4. 역전파 - 모든 가중치의 gradient 를 계산해 각 파라미터의 .grad에 채운다.
    loss.backward()

    # 5. 갱신 - .gard를 보고 모든 가중치를 한 번에 수정
    optimizer.step()

    # * 이 5줄이 모든 딥러닝의 뼈대다. 4주차 Mini GPT도 토씨 하나 안 다르다.

    # 400회마다 진행 상황 출력
    if epoch % 400 == 0 :
        print(f"epoch {epoch:>4} loss = {loss.item():.6f}")

# ─── 테스트 ───────────────────────────────────────────────
# torch.no_grad(): 더 이상 학습하지 않으므로 계산 그래프를 만들지 않는다.
# 메모리를 아끼고 속도도 빨라진다.

with torch.no_grad() :
    for test in ([6.,7.,8.], [10.,11.,12.]):
        # torch.tenser([test]) : [[6.,7.,8.]] 로 감싸 (1,3) 모양을 만든다.
        # 모델은 항상 '묶음(배치)' 단위 입력을 기대한다.
        out = model(torch.tensor([test])).item()
        print(f"입력 {test} -> 예측 {out:.3f}")

# ─── 관찰 포인트 ──────────────────────────────────────────
# [6,7,8] -> 9 는 꽤 맞힌다. 학습 데이터 범위(1~8)와 가깝기 때문이다.
# [10,11,12] -> 13 은 크게 빗나간다.
#
# 신경망은 "+1 씩 늘어난다"는 규칙을 '이해'한 게 아니라,
# 본 적 있는 숫자 범위 안에서 패턴을 '흉내'낼 뿐이다.
# 이것이 4주차에서 다룰 일반화의 한계이고,
# 7주차에서 RAG 가 필요한 이유이기도 하다 — 모델이 모르는 것은 밖에서 찾아다 줘야 한다.

# 10 11 12는 많이 빗나간다고 했는데, 오차 범위가 9와 비슷하다.
# 2001번 데이터를 가지고 확인하다가 오차가 너무 커서 40000번으로 올렸더니, 정확도가 조금은 올라갔다.