"""
파라미터1개짜리 경사하강법
라이브러리를 전혀 쓰지 않는다. '학습'이 실제로 무슨 계산인지 보기 위함

[문제]
x=2를 넣으면 10(t)이 나오게 하는 w를 찾아라. (정답은 w=5)
모델이 그 답을 '모르는 상태에서 스스로 찾아가는 과정'을 관찰한다.

[반복 1회 = 4단계]
1. 순전파 : 지금 w로 예측해본다 y = w * x
2. 손실 : 얼마나 틀렸나 숫자로 잰다 loss = (y - t)^2
3. 미분 : w를 늘리면 loss가 어찌 변하나 grad = 2(y - t) * x
4. 갱신 : grad 반대 방향으로 조금 이동 w = w - lr * grad
"""

# ---- 데이터와 초기값 ----
x, t = 2.0, 10.0 # x = 입력, t = 정답(target). 이 둘은 학습 중 변하지 않는다.
w = 1.0 # 학습할 파라미터. 아무 값에서 시작해도 된다.
lr = 0.1 # learning rate(학습률) = 한 번에 얼마나 움직일지 = 보폭

print(f"{'회차':>4} {'w':>9} {'예측':>8} {'Loss':>12} {'gradient':>10}")
print("-" * 48)

for step in range(11) :
    # 1. 순전파(forward) : 현재 w로 예측 값을 만든다
    y = w * x

    # 2. 손실(loss) : 예측과 정답의 차이를 제곱.
    # 제곱하는 이유 - 부호를 없애고 (2 모자라나 2 넘치나 똑같이 나쁨),
    #              큰 오차에 더 큰 벌점을 주고, 미분이 깔끔해진다.
    loss = (y - t) ** 2

    # 3. 미분(gradient) : loss를 w로 미분한 값.
    #    "w를 아주 조금 늘리면 loss가 얼마나 변하는가" 를 뜻한다.
    #
    #    유도 : loss = (w*x - t)^2
    #          연쇄법칙 -> d(loss)/dw = 2*(w*x - t) * x = 2*(y - t) * x
    #    부호 읽는 법 :
    #      grad > 0 : w를 늘리면 loss가 커진다 -> w를 줄여야 한다.
    #      grad < 0 : w를 늘리면 loss가 작아진다 -> w를 늘려야 한다.
    grad = 2 * (y - t) * x

    print(f"{step:>4} {w:>9.4f} {y:>8.4f} {loss:>12.6f} {grad:>10.4f}")

    # 4. 갱신(update) : grad의 '반대' 방향으로 lr 만큼 이동.
    #    빼기(-)를 쓰는 이유가 바로 '반대 방향'이다. 그래서 경사'하'강법
    #    grad가 음수면 w - lr*(음수) = w+양수 -> w가 커진다.
    #    grad가 양수면 w - lr*(양수)         -> w가 작아진다
    #    어느 쪽이든 loss가 줄어드는 방향으로 간다.
    w = w - lr * grad

    # 관찰 포인트 : 정답(5)에 가까워질수록 grad가 작아지고,
    #            따라서 보폭도 저절로 줄어든다.
    #            경사하강법은 별도 장치 없이 목표 근처에서 알아서 감속한다.